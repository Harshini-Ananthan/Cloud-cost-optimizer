import React, { useState } from 'react';
import { 
  Sparkles, 
  Copy, 
  Check, 
  ExternalLink, 
  ChevronRight, 
  Filter, 
  Search, 
  Sliders, 
  ShieldCheck, 
  AlertCircle,
  Terminal,
  Zap
} from 'lucide-react';
import { getGcpServiceIcon, RecommenderIcon } from './GcpIcons';

const GcpRecommendationsView = ({ 
  recommendations = [], 
  currency = 'INR',
  appliedFixes = {}, 
  onToggleApplyFix, 
  onNavigateToSimulator 
}) => {
  const [copiedId, setCopiedId] = useState(null);
  const [selectedCategory, setSelectedCategory] = useState('ALL');
  const [selectedService, setSelectedService] = useState('ALL');
  const [searchTerm, setSearchTerm] = useState('');

  const fmt = (val) => {
    const locale = currency === 'INR' ? 'en-IN' : 'en-US';
    return new Intl.NumberFormat(locale, {
      style: 'currency',
      currency: currency,
      maximumFractionDigits: 2
    }).format(val || 0);
  };

  const handleCopyCommand = (id, command) => {
    navigator.clipboard.writeText(command);
    setCopiedId(id);
    setTimeout(() => setCopiedId(null), 2500);
  };

  const categories = ['ALL', ...new Set(recommendations.map(r => r.category))];
  const services = ['ALL', ...new Set(recommendations.map(r => r.service))];

  const filtered = recommendations.filter(rec => {
    const matchesCat = selectedCategory === 'ALL' || rec.category === selectedCategory;
    const matchesSrv = selectedService === 'ALL' || rec.service === selectedService;
    const matchesSearch = searchTerm === '' || 
      rec.title.toLowerCase().includes(searchTerm.toLowerCase()) ||
      rec.detected_issue.toLowerCase().includes(searchTerm.toLowerCase()) ||
      rec.project_id.toLowerCase().includes(searchTerm.toLowerCase());
    return matchesCat && matchesSrv && matchesSearch;
  });

  const totalSavings = filtered.reduce((sum, r) => sum + (r.estimated_monthly_savings || 0), 0);

  return (
    <div className="gcp-recommendations-container">
      {/* 1. Active Assist Header & Savings Banner */}
      <div className="gcp-card-box">
        <div className="gcp-card-box-header">
          <div className="header-with-badge">
            <RecommenderIcon size={24} />
            <div>
              <h3 className="gcp-card-box-title">Google Cloud Active Assist Recommender</h3>
              <p className="gcp-card-box-desc">
                Automated prescriptive recommendations generated by Google Cloud FinOps heuristics and ML telemetry analysis.
              </p>
            </div>
          </div>

          <div className="total-savings-summary-pill">
            <span className="summary-label">Potential Monthly Reduction:</span>
            <span className="summary-val">{fmt(totalSavings)}/mo</span>
          </div>
        </div>

        {/* Filter controls */}
        <div className="recs-filter-bar">
          <div className="gcp-search-input-box">
            <Search size={15} />
            <input 
              type="text" 
              placeholder="Search recommendations by title, service, or project..." 
              value={searchTerm}
              onChange={(e) => setSearchTerm(e.target.value)}
            />
          </div>

          <div className="filter-select-group">
            <Filter size={15} />
            <select 
              value={selectedCategory} 
              onChange={(e) => setSelectedCategory(e.target.value)}
              className="gcp-service-dropdown"
            >
              {categories.map(c => (
                <option key={c} value={c}>Category: {c}</option>
              ))}
            </select>

            <select 
              value={selectedService} 
              onChange={(e) => setSelectedService(e.target.value)}
              className="gcp-service-dropdown"
            >
              {services.map(s => (
                <option key={s} value={s}>Service: {s}</option>
              ))}
            </select>
          </div>
        </div>
      </div>

      {/* 2. Recommendation Cards Grid */}
      <div className="recommendations-grid">
        {filtered.map((rec) => {
          const isApplied = !!appliedFixes[rec.id];
          const isCopied = copiedId === rec.id;

          return (
            <div key={rec.id} className={`gcp-recommendation-card ${isApplied ? 'card-applied' : ''}`}>
              {/* Card Header */}
              <div className="gcp-rec-header">
                <div className="rec-service-identity">
                  <div className="rec-icon-wrapper">
                    {getGcpServiceIcon(rec.service, 22)}
                  </div>
                  <div>
                    <span className="rec-service-name">{rec.service}</span>
                    <span className="rec-project-label">{rec.project_id}</span>
                  </div>
                </div>

                <div className="rec-badge-group">
                  <span className="rec-category-pill">{rec.category}</span>
                  <div className="rec-savings-highlight">
                    Save {fmt(rec.estimated_monthly_savings)}/mo
                  </div>
                </div>
              </div>

              {/* Title & Description */}
              <h3 className="rec-heading">{rec.title}</h3>
              
              <div className="rec-observation-box">
                <span className="obs-tag">Detected Waste Signature:</span>
                <p className="obs-text">{rec.detected_issue}</p>
              </div>

              <div className="rec-solution-box">
                <span className="sol-tag">Recommended FinOps Action:</span>
                <p className="sol-text">{rec.recommendation}</p>
              </div>

              {/* Execution Command (gcloud) */}
              {rec.gcloud_command && (
                <div className="rec-cli-box">
                  <div className="cli-header">
                    <span className="cli-title">
                      <Terminal size={13} />
                      <span>Instant gcloud Execution Command</span>
                    </span>
                    <button 
                      className={`copy-cli-btn ${isCopied ? 'copied' : ''}`}
                      onClick={() => handleCopyCommand(rec.id, rec.gcloud_command)}
                    >
                      {isCopied ? (
                        <>
                          <Check size={12} /> Copied!
                        </>
                      ) : (
                        <>
                          <Copy size={12} /> Copy Command
                        </>
                      )}
                    </button>
                  </div>
                  <pre className="cli-code"><code>{rec.gcloud_command}</code></pre>
                </div>
              )}

              {/* Card Footer Actions */}
              <div className="rec-card-footer">
                <div className="rec-meta-tags">
                  <span className="meta-tag">Effort: <strong>{rec.effort}</strong></span>
                  <span className="meta-tag">Risk: <strong>{rec.risk}</strong></span>
                </div>

                <div className="rec-actions-right">
                  <a 
                    href={rec.console_url} 
                    target="_blank" 
                    rel="noopener noreferrer"
                    className="gcp-console-link"
                  >
                    Console <ExternalLink size={13} />
                  </a>

                  <button 
                    className="sim-action-btn"
                    onClick={() => onNavigateToSimulator && onNavigateToSimulator(rec)}
                  >
                    <Sliders size={13} /> Simulate
                  </button>

                  <button 
                    className={`apply-fix-btn ${isApplied ? 'applied' : ''}`}
                    onClick={() => onToggleApplyFix && onToggleApplyFix(rec.id)}
                  >
                    {isApplied ? (
                      <>
                        <Check size={14} /> Remediated
                      </>
                    ) : (
                      'Mark Applied'
                    )}
                  </button>
                </div>
              </div>
            </div>
          );
        })}
      </div>
    </div>
  );
};

export default GcpRecommendationsView;
